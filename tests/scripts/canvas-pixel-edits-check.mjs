import { app, BrowserWindow } from 'electron';
import esbuild from 'esbuild';
import path from 'node:path';
import os from 'node:os';
import fs from 'node:fs';
const electronData = path.join(os.tmpdir(), 'nai-atelier-canvas-pixel-check');
fs.mkdirSync(electronData, { recursive: true });
app.setPath('userData', electronData);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { sandbox: false } });
  await win.loadURL('data:text/html,<html><body></body></html>');
  const bundle = esbuild.buildSync({ stdin: { contents: "export * from './services/canvasEngine'; export * from './services/canvasPixelEdits';", resolveDir: path.resolve('.'), loader: 'ts' }, bundle: true, write: false, platform: 'browser', format: 'iife', globalName: 'engine' }).outputFiles[0].text;
  await win.webContents.executeJavaScript(bundle);
  const result = await win.webContents.executeJavaScript(`(async () => {
    const source = document.createElement('canvas'); source.width = 20; source.height = 10;
    const ctx = source.getContext('2d'); ctx.fillStyle = '#f00'; ctx.fillRect(0,0,10,10); ctx.fillStyle = '#00f'; ctx.fillRect(10,0,10,10);
    const base = {...await engine.createImageLayer(source.toDataURL(), 80, 80), x:30, y:30, rotation:90, scaleX:-1, scaleY:1.5, opacity:.5};
    let layer = base;
    const at = (x,y) => engine.layerToProject(base,{x,y});
    const selection = {points:[at(0,0),at(5,0),at(5,10),at(0,10)]};
    const zero = at(0,0), destination = at(22,0), delta = {x:destination.x-zero.x,y:destination.y-zero.y};
    const project = {version:1,id:'p',name:'p',width:80,height:80,background:{kind:'transparent',color:''},layers:[layer],updatedAt:0};
    const sample = async (item,x,y) => { const c=await engine.renderProject({...project,layers:[item]}); const p=at(x,y); return Array.from(c.getContext('2d').getImageData(Math.floor(p.x),Math.floor(p.y),1,1).data); };
    const alpha = async (item,x,y) => (await sample(item,x,y))[3];
    const before = await alpha(layer,2,5);
    layer = engine.moveCanvasSelection(layer,selection,delta);
    const moved = await alpha(layer,24,5), cleared = await alpha(layer,2,5), unaffected = await alpha(layer,8,5);
    const hitMoved = await engine.hitCanvasLayer(layer, at(24,5)), hitCleared = await engine.hitCanvasLayer(layer, at(2,5));
    const stroke={points:[at(24,5)],size:4,mode:'erase'};
    const preview=await engine.renderProject({...project,layers:[layer]},{layerId:layer.id,stroke,selection:null});
    layer=await engine.applyBrush(layer,stroke,null);
    const erased=await alpha(layer,24,5);
    const previewAlpha=preview.getContext('2d').getImageData(Math.floor(at(24,5).x),Math.floor(at(24,5).y),1,1).data[3];
    layer=await engine.applyBrush(layer,{...stroke,mode:'restore'},null);
    const restored=await alpha(layer,24,5);
    const serial=JSON.parse(JSON.stringify(layer));
    const roundtrip=await alpha(serial,24,5);
    const secondSel={points:selection.points.map(p=>({x:p.x+delta.x,y:p.y+delta.y}))};
    layer=engine.moveCanvasSelection(layer,secondSel,{x:-delta.x/2,y:-delta.y/2});
    const movedAgain=await alpha(layer,13,5), secondCleared=await alpha(layer,24,5);
    const crop=engine.cropImageLayer(layer,{points:[at(11,0),at(16,0),at(16,10),at(11,10)]});
    const cropInside=await alpha(crop,13,5), cropOutside=await alpha(crop,8,5);
    let oldMask=await engine.applyBrush(base,{points:[at(2,5)],size:4,mode:'erase'},null);
    oldMask=engine.moveCanvasSelection(oldMask,selection,delta);
    const oldEraseMoved=await alpha(oldMask,24,5);
    oldMask=await engine.applyBrush(oldMask,{points:[at(24,5)],size:4,mode:'restore'},null);
    const oldEraseRestored=await alpha(oldMask,24,5);
    const overlap = engine.moveCanvasSelection(base,selection,{x:at(3,0).x-zero.x,y:at(3,0).y-zero.y});
    const overlapCleared=await alpha(overlap,1,5), overlapMoved=await alpha(overlap,4,5);
    return {before,moved,cleared,unaffected,hitMoved,hitCleared,erased,previewAlpha,restored,roundtrip,movedAgain,secondCleared,cropInside,cropOutside,oldEraseMoved,oldEraseRestored,overlapCleared,overlapMoved};
  })()`);
  console.log(JSON.stringify(result));
  if (!(result.before >= 120 && result.moved >= 120 && result.cleared === 0 && result.unaffected >= 120 && result.hitMoved && !result.hitCleared && result.erased === 0 && result.previewAlpha === result.erased && result.restored >= 120 && result.roundtrip === result.restored && result.movedAgain >= 120 && result.secondCleared === 0 && result.cropInside >= 120 && result.cropOutside === 0 && result.oldEraseMoved === 0 && result.oldEraseRestored >= 120 && result.overlapCleared === 0 && result.overlapMoved >= 120)) process.exitCode = 1;
  win.destroy(); app.quit();
}).catch(error => { console.error(error); process.exitCode = 1; app.quit(); });
